#!/bin/sh
# Writes Config/Pulse.xcconfig.local (git-ignored) from Backend/rag/.env, so builds made on this Mac can call
# OpenRouter and Cartesia directly. Keep such builds on your own phones: the keys are readable inside the app.
set -eu
root=$(cd "$(dirname "$0")/../.." && pwd)
env="$root/Backend/rag/.env"
out="$root/Config/Pulse.xcconfig.local"
value() { grep "^$1=" "$env" | head -1 | cut -d= -f2-; }
umask 077
{
  echo "// Generated by Tools/Pulse/write_app_keys.sh from Backend/rag/.env. Git-ignored; never commit."
  echo "PULSE_OPENROUTER_KEY = $(value OPENROUTER_API_KEY)"
  echo "PULSE_CARTESIA_KEY = $(value CARTESIA_API_KEY)"
  echo "PULSE_CARTESIA_BACKUP_KEY = $(value CARTESIA_API_KEY_BACKUP)"
  echo "PULSE_TOMTOM_KEY = $(value TOMTOM_API_KEY)"
} > "$out"
echo "Wrote $out"
